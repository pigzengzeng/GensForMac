static const char **glyph_for(char c)
{
  unsigned int i = (unsigned char)c;
  if (i < 128 && FONT[i][0]) return FONT[i];
  return DEF;
}

int font_width(const char *text, int scale)
{
  if (!text) return 0;
  int n = (int)strlen(text);
  if (n == 0) return 0;
  return n * 8 * scale + (n - 1) * scale;   /* 8 px glyph + 1 px gap */
}

int font_height(int scale) { return 8 * scale; }

void font_draw(SDL_Renderer *r, int x, int y, const char *text,
               int scale, SDL_Color c)
{
  if (!text || !*text) return;
  SDL_SetRenderDrawColor(r, c.r, c.g, c.b, c.a);
  int cx = x;
  for (const char *p = text; *p; p++) {
    char ch = *p;
    if (ch >= 'a' && ch <= 'z') ch = (char)(ch - 32);   /* uppercase */
    const char *const *rows = (const char *const *)glyph_for(ch);
    for (int row = 0; row < 8; row++) {
      const char *line = rows[row];
      for (int col = 0; col < 8; col++) {
        if (line[col] == '#') {
          SDL_Rect rect = { cx + col * scale, y + row * scale, scale, scale };
          SDL_RenderFillRect(r, &rect);
        }
      }
    }
    cx += 9 * scale;
  }
}
